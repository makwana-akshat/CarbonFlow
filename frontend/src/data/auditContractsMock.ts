export type AuditContractStatus =
  | 'Draft'
  | 'Pending Review'
  | 'Approved'
  | 'Active'
  | 'Completed'
  | 'Expired'
  | 'Cancelled';

export interface ComplianceSummary {
  activeContracts: number;
  pendingApproval: number;
  completed: number;
  withAmendments: number;
}

export interface AuditTimelineEvent {
  step: number;
  label: string;
  timestamp: string;
  actor: string;
  role: string;
  action: string;
  notes?: string;
  status: 'completed' | 'in-progress' | 'upcoming';
}

export interface ContractVersionInfo {
  version: string;
  isCurrent: boolean;
  summary: string;
  effectiveDate: string;
  author: string;
  changes: string[];
}

